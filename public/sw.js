// Al instalarse se guarda todo lo necesario para funcionar sin conexión. Se
// guarda archivo a archivo: si alguno fallara, la app se instala igual y ese
// archivo se guarda la primera vez que se use.
self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.allSettled(OFFLINE.map((u) => c.add(new Request(u, { cache: 'reload' }))));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((claves) => Promise.all(claves.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;

  // Inmutables: caché primero
  if (/^\/(vendor|fuentes|iconos)\//.test(url.pathname)) {
    e.respondWith(caches.open(CACHE).then(async (c) => {
      const guardada = await c.match(req, { ignoreSearch: true });
      if (guardada) return guardada;
      const resp = await fetch(req);
      if (resp.ok) c.put(req, resp.clone());
      return resp;
    }));
    return;
  }

  // Interfaz: red primero, caché si no hay conexión
  e.respondWith(
    fetch(req)
      .then((resp) => {
        if (resp.ok) { const copia = resp.clone(); caches.open(CACHE).then((c) => c.put(req, copia)); }
        return resp;
      })
      .catch(async () => (await caches.match(req, { ignoreSearch: true })) || (req.mode === 'navigate' ? caches.match('/') : Response.error())),
  );
});
